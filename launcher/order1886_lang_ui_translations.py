"""Translations for the high-traffic, low-risk subset of the launcher UI.

`launcher/order1886_lang_ui.py` catalogues every string the Go frontend and the
settings catalogue can show, but only the English text exists for them, so every
language falls back to English. This module translates the part of that catalogue a
player actually reads first - page titles, navigation words, section headings, button
labels, action verbs, short state words and short unambiguous field labels - and leaves
every diagnostic, description, availability reason and warning paragraph in English on
purpose. The rule, the included list and the excluded classes are written down in
docs/order1886-localization-policy.md.

Provenance: like the existing tables in `launcher/order1886_lang_data.py`, these are
machine-assisted translations that no native speaker has reviewed. Treat a surprising
wording as a candidate for review, not as an authority. Field descriptions are not
translated on purpose: a mistranslated diagnostic is worse than English when a player
is troubleshooting, so those strings stay English until a person owns them.

The keys here must be a subset of `UI_KEYS`; tests/test_order1886_lang_ui_translations.py
enforces that, the exclusion list below, and the untranslated() count per language.
"""

