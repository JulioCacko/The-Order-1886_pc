"""Build an original geometric launcher icon; never embed extracted game art."""
from pathlib import Path
import sys
from PIL import Image, ImageDraw


def create_icon(destination: Path):
    destination.mkdir(parents=True, exist_ok=True)
    image = Image.new("RGBA", (256, 256), "#0b0b0a")
    draw = ImageDraw.Draw(image)
    gold, muted = "#d4bd75", "#74633e"
    draw.rounded_rectangle((6, 6, 249, 249), radius=36, outline=muted, width=3)
    draw.rounded_rectangle((15, 15, 240, 240), radius=29, outline=gold, width=2)
    draw.ellipse((59, 38, 196, 217), outline=gold, width=9)
    draw.ellipse((79, 55, 176, 200), outline=muted, width=2)
    draw.line((128, 22, 128, 72), fill=gold, width=3)
    draw.line((128, 183, 128, 234), fill=gold, width=3)
    draw.polygon(((128, 99), (151, 128), (128, 156), (105, 128)), outline=gold, width=3)
    image.save(destination / "order1886.ico", sizes=[(16,16), (24,24), (32,32), (48,48), (64,64), (128,128), (256,256)])
    (destination / "ARTWORK.txt").write_text(
        "Original geometric black-and-gold launcher monogram. Generated by "
        "packaging/windows/order1886_icon.py, licensed under GPL-2.0-or-later.\n"
        "Game artwork is loaded only from the player's selected game folder.\n", encoding="utf-8")


if __name__ == "__main__":
    create_icon(Path(sys.argv[1]))
